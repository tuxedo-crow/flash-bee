#!/usr/bin/env bash
# Write FlashBee/build_stamp.h with the git commit and UTC build time. flash.sh calls it before the compile;
# run it alone ("bash stamp.sh") to refresh the stamp for an Arduino CLI build. The file is git-ignored.
set -u
ROOT="$(cd "$(dirname "$0")" && pwd)"
OUT="$ROOT/FlashBee/build_stamp.h"
SHA="unknown"
if command -v git >/dev/null 2>&1 && git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1; then
  SHA="$(git -C "$ROOT" rev-parse --short=7 HEAD 2>/dev/null || echo unknown)"
  # Tracked changes only; build_stamp.h is git-ignored, so it never counts.
  if [ "$SHA" != "unknown" ] && [ -n "$(git -C "$ROOT" status --porcelain --untracked-files=no 2>/dev/null)" ]; then
    SHA="$SHA-dirty"
  fi
fi
cat > "$OUT" <<H
// Generated by stamp.sh (git-ignored). Do not edit.
#define BUILD_GIT "$SHA"
#define BUILD_DATE "$(date -u '+%Y-%m-%d %H:%M')"
H
echo "Build stamp: $SHA ($OUT)"
